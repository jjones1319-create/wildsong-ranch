/**
 * GAME_DESIGN §13: tournaments and ranks. A cup lives in the save while it is played: its participants
 * (generated by the seed (year, week, cup id)), its schedule and the results so far. The player's matches are
 * fought on the battle screen; NPC-only matches run through the engine here. `finishTournament` applies
 * everything a cup changes: purse and item prizes, fame, stat growth, after-effects, promotion, rank,
 * invitations, the Hall of Fame, titles and mastery.
 */

export const gradeIndex = (g: TournamentGrade): number => TOURNAMENT_GRADES.indexOf(g) + 1

export type EntryBlock = 'noMonster' | 'inTournament' | 'journey' | 'injured' | 'sick' | 'away' | 'gradeTooHigh' | 'minGrade' | 'invitation' | 'rule' | 'noTechniques'

export interface WeekEventView {
  event: TournamentEvent
  eligible: boolean
  reason: EntryBlock | null
  /** Entering below your grade costs fame and loyalty (§13). */
  tooEasy: boolean
  /** The grade the opponents are made at. */
  opponentGrade: NpcGrade
  purse: number
}

export function weekInYear(week: number): number {
  return week % WEEKS_PER_YEAR
}

/** 1st-place purse after the grade scaling of Officials and the Summit Qualifier. */
export function purseOf(event: TournamentEvent, playerGrade: TournamentGrade): number {
  if (event.kind === 'official') return TOURNAMENT.officialPursePerGrade * gradeIndex(playerGrade)
  if (event.kind === 'summitQualifier') return TOURNAMENT.summit.qualifierPerGrade * gradeIndex(playerGrade)
  if (event.kind === 'summit') return TOURNAMENT.summit.teamWin
  return event.purse
}

export function opponentGradeOf(event: TournamentEvent, playerGrade: TournamentGrade): NpcGrade {
  if (event.kind === 'legend') return 'Legend'
  if (event.kind === 'crown') return 'Crown'
  if (event.grade === 'own' || event.grade === 'any') return playerGrade
  return event.grade
}

function typeOnly(event: TournamentEvent): 'POW' | 'INT' | null {
  return event.rule === 'powOnly' ? 'POW' : event.rule === 'intOnly' ? 'INT' : null
}

/** The monster as it fights in this cup (POW-only and INT-only cups strip the other type). */
export function fightingCopy(m: Monster, event: TournamentEvent): Monster {
  const copy = structuredClone(m)
  const only = typeOnly(event)
  if (only) copy.techniques = copy.techniques.filter((t) => TECHNIQUE_BY_ID[t.id]?.type === only)
  return copy
}

export interface EntryCheck {
  eligible: boolean
  reason: EntryBlock | null
  /** Entering below your grade costs fame and loyalty (§13). */
  tooEasy: boolean
}

/** The blocks that change from week to week (a cup in progress, a Journey, injury, sickness, being away). */
export const TEMPORARY_BLOCKS: readonly EntryBlock[] = ['inTournament', 'journey', 'injured', 'sick', 'away']

/**
 * §13 entry rules for one event held in week `at` (absolute). For this week every rule applies. For a later
 * week (the calendar) only what is knowable today is checked: the grade window, "too easy", the minimum grade,
 * invitations and the event's rule; the monster's age is projected to that week, and its grade, nature and
 * techniques are today's. The temporary blocks (a cup in progress, a Journey, injury, sickness, away) are skipped.
 */
export function entryCheck(state: GameState, event: TournamentEvent, at: number = state.week): EntryCheck {
  const m = state.monster
  const no = (reason: EntryBlock): EntryCheck => ({ eligible: false, reason, tooEasy: false })
  if (!m) return no('noMonster')
  if (at <= state.week) {
    if (state.tournament) return no('inTournament')
    if (state.journey) return no('journey')
    if (m.status.injuredWeeks > 0) return no('injured')
    if (m.status.sickWeeks > 0) return no('sick')
    if (m.status.missingWeeks > 0 || m.status.clinicWeeks > 0 || m.status.cocoonWeeks > 0 || state.expedition) return no('away')
  }
  const grade = m.grade
  if (event.kind === 'masquerade' && !state.unlocks.masqueradeInvited) return no('invitation')
  if (event.kind === 'crown' && !(grade === 'S' && state.guild.crownInvite)) return no('invitation')
  if (event.kind === 'legend' && !state.guild.legendInvite) return no('invitation')
  if (event.minGrade && gradeIndex(grade) < gradeIndex(event.minGrade)) return no('minGrade')
  let tooEasy = false
  if (event.grade !== 'own' && event.grade !== 'any' && event.kind === 'cup') {
    const diff = gradeIndex(event.grade) - gradeIndex(grade)
    if (diff > 1) return no('gradeTooHigh')
    tooEasy = diff < 0
  }
  const age = m.ageWeeks + Math.max(0, at - state.week)
  switch (event.rule) {
    case 'sprout':
      if (age >= 48) return no('rule')
      break
    case 'elders':
      if (age < 288) return no('rule')
      break
    case 'hero':
      if (m.nature < 20) return no('rule')
      break
    case 'rogue':
      if (m.nature > -20) return no('rule')
      break
    case 'powOnly':
    case 'intOnly':
      if (fightingCopy(m, event).techniques.length === 0) return no('noTechniques')
      break
    default:
      break
  }
  return { eligible: true, reason: null, tooEasy }
}

/** This week's events with eligibility and the reason when not (§13 entry rules). Eligible ones first. */
export function eventsForWeek(state: GameState): WeekEventView[] {
  const d = dateOf(state.week)
  const grade = state.monster?.grade ?? 'E'
  const views = eventsAt(weekInYear(state.week), d.year).map((event): WeekEventView => ({ event, opponentGrade: opponentGradeOf(event, grade), purse: purseOf(event, grade), ...entryCheck(state, event) }))
  return views.sort((a, b) => Number(b.eligible) - Number(a.eligible))
}

/** How many rounds a format plays: a round robin of n has n − 1, an elimination of n has log₂ n, a single match 1. */
export function roundsOf(format: TournamentEvent['format']): number {
  const n = formatSize(format).participants
  if (format === 'RR4' || format === 'RR6') return n - 1
  if (format === 'Elim4' || format === 'Elim8') {
    let rounds = 0
    for (let k = 1; k < n; k *= 2) rounds += 1
    return rounds
  }
  return 1
}

/** What 1st place wins on top of the purse (§13 item prizes), by event kind and the monster's grade. */
export type ItemPrizeKind = 'sweets' | 'sheetOrGrand' | 'grandSweets' | 'wondercake' | 'signature' | 'legend' | 'shardMask' | 'none'

export function itemPrizeKind(event: TournamentEvent, grade: TournamentGrade): ItemPrizeKind {
  switch (event.kind) {
    case 'summit':
      return 'none'
    case 'official':
      return 'wondercake'
    case 'crown':
      return 'signature'
    case 'legend':
      return 'legend'
    case 'masquerade':
      return 'shardMask'
    default: {
      const gi = gradeIndex(grade)
      return gi <= 2 ? 'sweets' : gi <= 4 ? 'sheetOrGrand' : 'grandSweets'
    }
  }
}

/* ---------- participants ---------- */

export function cupSeed(week: number, eventId: string): number {
  const d = dateOf(week)
  return cyrb53(`${d.year}-${weekInYear(week)}-${eventId}`, 1)
}

const MAX_TOTAL = RANGES.stat.max * 6

/**
 * A total scaled from the player's (percent), never below the grade's band (M9: the special cups stay a
 * challenge for a monster far above its band).
 */
function scaledTotal(player: Monster, grade: NpcGrade, pct: number): number {
  const band = NPC.totals[grade]!
  return clamp(divRound(totalStats(player.stats) * pct, 100), band[0], MAX_TOTAL)
}

/** The special cups' opponents follow the player's total; every other cup uses the grade's band. */
function specialTotal(player: Monster, event: TournamentEvent, grade: NpcGrade): number | undefined {
  const pct = (TOURNAMENT.specialScalePct as Partial<Record<string, number>>)[event.kind]
  return pct === undefined ? undefined : scaledTotal(player, grade, pct)
}

function corinFor(player: Monster, event: TournamentEvent, grade: NpcGrade, rng: Rng): Participant {
  const special = event.kind === 'crown' || event.kind === 'legend'
  const breed = special ? (CORIN.crownBreed ?? CORIN.breed) : CORIN.breed
  const band = NPC.totals[grade]!
  const scaled = scaledTotal(player, grade, RIVAL_TUNING.corinScalePct)
  // In the Officials Corin stays inside the grade's band; at the Crowns he follows the player all the way.
  const total = special ? scaled : Math.min(scaled, band[1])
  const monster = npcMonster({ breed, grade, total, seed: rng.nextU32(), name: CORIN.name.split(' ')[0] })
  const personality: Personality = gradeIndex(player.grade) >= gradeIndex(RIVAL_TUNING.corinAggressiveFrom) && CORIN.personalityFromA ? CORIN.personalityFromA : CORIN.personality
  return { name: CORIN.name, monster, personality, habit: CORIN.habit, rivalId: CORIN.id, player: false }
}

function wildParticipant(grade: NpcGrade, rng: Rng, boss = false, total?: number): Participant {
  const breed = rng.weightedPick(BREEDS, (b) => b.commonness).id
  const name = rng.pick(WILD_NAMES)
  const monster = npcMonster({ breed, grade, total, seed: rng.nextU32(), boss, name })
  return { name, monster, personality: rng.pick(['Steady', 'Aggressive', 'Cautious', 'Trickster', 'Sniper', 'Brawler'] as const), habit: 'none', rivalId: null, player: false }
}

function rivalParticipant(rivalId: string, grade: NpcGrade, rng: Rng, total?: number): Participant {
  const r = RIVAL_BY_ID[rivalId]!
  const monster = npcMonster({ breed: r.breed, grade, total, seed: rng.nextU32(), name: r.name.split(' ')[0] })
  return { name: r.name, monster, personality: r.personality, habit: r.habit, rivalId: r.id, player: false }
}

/** Opponents for a cup: Corin where the rules put him, eligible rivals by chance, wild monsters for the rest. */
export function makeOpponents(state: GameState, event: TournamentEvent, rng: Rng): Participant[] {
  const player = state.monster!
  const grade = opponentGradeOf(event, player.grade)
  const count = formatSize(event.format).participants - 1
  const out: Participant[] = []
  if (event.kind === 'rival' || event.kind === 'official' || event.kind === 'crown') out.push(corinFor(player, event, grade, rng))
  const special = specialTotal(player, event, grade)
  if (event.kind === 'legend') out.push(wildParticipant('Legend', rng, true, special))
  // CONTENT §10, §11: the Masquerade Cup is a single match against the Masked Breeder's Mirrorkin, scaled to you.
  if (event.kind === 'masquerade') out.push(rivalParticipant('masked-breeder', grade, rng, special))
  if (event.kind === 'cup' && event.grade !== 'any') {
    const eligible = RIVALS.filter((r) => r.special === null && r.grades.includes(event.grade as TournamentGrade))
    for (const r of eligible) {
      if (out.length >= Math.min(count, TOURNAMENT.rivals.maxPerCup)) break
      if (rng.chance(TOURNAMENT.rivals.chancePct)) out.push(rivalParticipant(r.id, grade, rng))
    }
  }
  while (out.length < count) {
    let g: NpcGrade = grade
    if (event.grade === 'any' && event.kind !== 'legend') {
      const i = clamp(TOURNAMENT_GRADES.indexOf(player.grade) + rng.nextInt(-TOURNAMENT.openSpread, TOURNAMENT.openSpread), 0, TOURNAMENT_GRADES.length - 1)
      g = TOURNAMENT_GRADES[i]!
    }
    out.push(wildParticipant(g, rng, false, special))
  }
  return out.slice(0, count)
}

/* ---------- schedules ---------- */

/** The cup's boss for scheduling: Corin when he is in the cup, else the opponent with the highest stat total (the lower index on a tie). */
export function bossIndex(participants: readonly Participant[]): number {
  const corin = participants.findIndex((p) => p.rivalId === CORIN.id)
  if (corin > 0) return corin
  let best = 1
  for (let i = 2; i < participants.length; i++) if (totalStats(participants[i]!.monster.stats) > totalStats(participants[best]!.monster.stats)) best = i
  return best
}

/**
 * §13 round robin by the circle method (n even): n − 1 rounds of n / 2 matches. Every pair meets once and
 * everyone, the player included, fights once per round. The opponents' seats come from the cup's seed; the round
 * in which the player meets the boss is played last. Within a round the player's match comes first, and a
 * match's `a` is always its lower index, so the player is side `a`.
 */
export function roundRobinSchedule(participants: readonly Participant[], rng: Rng): MatchRecord[] {
  const n = participants.length
  let ring = [0, ...rng.shuffle(Array.from({ length: n - 1 }, (_, i) => i + 1))]
  const rounds: [number, number][][] = []
  for (let r = 0; r < n - 1; r++) {
    const pairs: [number, number][] = []
    for (let i = 0; i < n / 2; i++) {
      const x = ring[i]!
      const y = ring[n - 1 - i]!
      pairs.push(x < y ? [x, y] : [y, x])
    }
    pairs.sort((p, q) => p[0] - q[0] || p[1] - q[1])
    rounds.push(pairs)
    // Seat 0 stays put; everyone else moves one seat round the table.
    ring = [ring[0]!, ring[n - 1]!, ...ring.slice(1, n - 1)]
  }
  const boss = bossIndex(participants)
  const last = rounds.findIndex((pairs) => pairs.some(([a, b]) => a === 0 && b === boss))
  const ordered = last < 0 ? rounds : [...rounds.slice(0, last), ...rounds.slice(last + 1), rounds[last]!]
  return ordered.flatMap((pairs, r) => pairs.map(([a, b]): MatchRecord => ({ round: r + 1, a, b, result: null })))
}

/** The first elimination round: the player faces a random opponent; the others pair off. */
function firstRound(n: number, rng: Rng): MatchRecord[] {
  const others = rng.shuffle(Array.from({ length: n - 1 }, (_, i) => i + 1))
  const matches: MatchRecord[] = [{ round: 1, a: 0, b: others[0]!, result: null }]
  for (let i = 1; i + 1 < others.length; i += 2) matches.push({ round: 1, a: others[i]!, b: others[i + 1]!, result: null })
  return matches
}

export function isElimination(t: TournamentState): boolean {
  const f = EVENT_BY_ID[t.eventId]!.format
  return f === 'Elim4' || f === 'Elim8'
}

/** Builds the cup: participants, schedule, the "too easy" entry cost. The state is not changed here. */
export function createTournament(state: GameState, eventId: string, mode: 'auto' | 'manual'): TournamentState {
  const event = EVENT_BY_ID[eventId]!
  const seed = cupSeed(state.week, eventId)
  const rng = createRng(seed)
  const player: Participant = { name: state.breeder.name, monster: fightingCopy(state.monster!, event), personality: 'Steady', habit: 'none', rivalId: null, player: true }
  const participants = [player, ...makeOpponents(state, event, rng)]
  const n = participants.length
  const matches = event.format === 'RR4' || event.format === 'RR6' ? roundRobinSchedule(participants, rng) : event.format === 'Elim4' || event.format === 'Elim8' ? firstRound(n, rng) : [{ round: 1, a: 0, b: 1, result: null }]
  return { eventId, week: state.week, seed, mode, participants, matches, koOut: [], eliminated: [], relayWins: 0, done: false }
}

/**
 * §12.10 the AI tier of a cup participant: the player's own side (Auto) is always expert, rivals are expert from
 * grade C, every opponent in a Crown, the Masquerade or the Legend Cup is expert, and wild monsters follow
 * their grade (E–D rookie, C–B skilled, A–S expert).
 */
export function tierFor(p: Participant, event: TournamentEvent): AiTier {
  if (p.player) return 'expert'
  if (event.kind === 'crown' || event.kind === 'legend' || event.kind === 'masquerade') return 'expert'
  if (p.rivalId && gradeIndex(p.monster.grade) >= gradeIndex('C')) return 'expert'
  return tierOfGrade(p.monster.grade)
}

/** §12.10 a Journey Trial opponent is expert from grade B. */
export function trialTier(grade: TournamentGrade): AiTier {
  return gradeIndex(grade) >= gradeIndex('B') ? 'expert' : tierOfGrade(grade)
}

/** The engine's default tier for a grade (its index is 0-based; `gradeIndex` here is 1-based). */
const tierOfGrade = (g: TournamentGrade): AiTier => tierForGrade(TOURNAMENT_GRADES.indexOf(g))

/** The next unplayed match with the player in it, if the player is still in the cup. */
export function nextPlayerMatch(t: TournamentState): { index: number; match: MatchRecord } | null {
  if (t.koOut.includes(0) || t.eliminated.includes(0)) return null
  const index = t.matches.findIndex((m) => m.result === null && (m.a === 0 || m.b === 0))
  return index >= 0 ? { index, match: t.matches[index]! } : null
}

export function opponentOf(t: TournamentState, match: MatchRecord): Participant {
  return t.participants[match.a === 0 ? match.b : match.a]!
}

/* ---------- rounds ---------- */

/** The round being played: the lowest round with an unplayed match, or null once every match has a result. */
export function currentRound(t: TournamentState): number | null {
  let r: number | null = null
  for (const m of t.matches) if (m.result === null && (r === null || m.round < r)) r = m.round
  return r
}

/** How many rounds the cup has: RR4 3, RR6 5, Elim4 2, Elim8 3, a 1v1 or the Summit leg 1 (a pre-v9 round robin keeps its stored count). */
export function roundCount(t: TournamentState): number {
  if (isElimination(t)) {
    let rounds = 0
    for (let k = 1; k < t.participants.length; k *= 2) rounds += 1
    return rounds
  }
  return t.matches.reduce((mx, m) => Math.max(mx, m.round), 1)
}

/** The last round whose every match has a result (0 before the first round ends; the round count once the cup is over). */
export function roundsDone(t: TournamentState): number {
  const r = currentRound(t)
  return r === null ? roundCount(t) : r - 1
}

/** The player's match in a round (played or not), or null when the player has none there. */
export function playerMatchIn(t: TournamentState, round: number): number | null {
  const i = t.matches.findIndex((m) => m.round === round && (m.a === 0 || m.b === 0))
  return i >= 0 ? i : null
}

/** True when the player can't fight again in this cup (KO'd, eliminated, or every match of theirs is played). */
export function playerIsDone(t: TournamentState): boolean {
  return nextPlayerMatch(t) === null
}

/* ---------- match setups (one place, so Fight, Auto, Skip and a replay are the same battle) ---------- */

export interface MatchSetup {
  a: FighterSetup
  b: FighterSetup
  options: BattleOptions
}

export interface PlayerMatchSetup {
  /** Battle side 0. */
  player: FighterSetup
  /** Battle side 1. */
  opponent: FighterSetup
  options: BattleOptions
  /** Whether the player is the match's `a` (results are stored from `a`'s point of view). */
  playerIsA: boolean
  opponentIndex: number
}

/** Each match fights on its own seed from the cup's seed and its place in the schedule. */
export function matchSeed(t: TournamentState, index: number): number {
  return cyrb53(`${t.seed}-${index}`, 2)
}

export function matchOptions(seed: number): BattleOptions {
  return { seed, timerTicks: timerTicksFor(TOURNAMENT.matchSeconds) }
}

function npcFighter(p: Participant, event: TournamentEvent): FighterSetup {
  return { monster: p.monster, control: 'ai', personality: p.personality, habit: p.habit, tier: tierFor(p, event) }
}

/** A match with both sides on the CPU, exactly as the cup simulates it (also used to replay it on screen). */
export function matchSetup(t: TournamentState, index: number): MatchSetup {
  const match = t.matches[index]!
  const event = EVENT_BY_ID[t.eventId]!
  return { a: npcFighter(t.participants[match.a]!, event), b: npcFighter(t.participants[match.b]!, event), options: matchOptions(matchSeed(t, index)) }
}

/**
 * §12.11 the player's side: always under the player's control, expert, with the saved Auto style. Auto is the
 * engine's `auto` flag, switched on by an input at the first tick, so the player can take over at any moment and a
 * replay stays exact.
 */
export function playerFighter(monster: Monster, style: AutoStyle): FighterSetup {
  return { monster, control: 'player', personality: 'Steady', tier: 'expert', style }
}

/** Auto from the first tick, as an input (the battle screen records it like a tap on Auto). */
export function autoStartInput(style: AutoStyle): BattleInput {
  return { tick: 1, side: 0, action: { kind: 'auto', on: true, style } }
}

/** The player's match: the player on battle side 0, the opponent on side 1, the match's own seed. */
export function playerMatchSetup(t: TournamentState, index: number, style: AutoStyle): PlayerMatchSetup {
  const match = t.matches[index]!
  const playerIsA = match.a === 0
  const opponentIndex = playerIsA ? match.b : match.a
  const event = EVENT_BY_ID[t.eventId]!
  return {
    player: playerFighter(t.participants[0]!.monster, style),
    opponent: npcFighter(t.participants[opponentIndex]!, event),
    options: matchOptions(matchSeed(t, index)),
    playerIsA,
    opponentIndex,
  }
}

/** A finished battle with the player on side 0, stored from the match's `a` side. */
export function playerMatchResult(outcome: BattleOutcome, playerIsA: boolean): MatchResult {
  const winner = outcome.winner === null ? null : ((playerIsA ? outcome.winner : 1 - outcome.winner) as 0 | 1)
  const hpPct: [number, number] = playerIsA ? [outcome.hpPct[0], outcome.hpPct[1]] : [outcome.hpPct[1], outcome.hpPct[0]]
  return { winner, how: outcome.how, hpPct, ticks: outcome.ticks }
}

/** Skip: the player's match simulated at once, exactly as an untouched Auto run on the same seed plays it. */
export function skipPlayerMatch(t: TournamentState, index: number, style: AutoStyle): TournamentState {
  const s = playerMatchSetup(t, index, style)
  const r = runBattle(s.player, s.opponent, s.options, [autoStartInput(style)])
  return recordMatch(t, index, playerMatchResult(r.outcome, s.playerIsA), r.fighters[0].techUses)
}

/** A result from the engine, seen from the match's `a` side. */
export function matchResultFrom(r: BattleResult, aIsSide0: boolean): MatchResult {
  const winner = r.outcome.winner === null ? null : ((aIsSide0 ? r.outcome.winner : 1 - r.outcome.winner) as 0 | 1)
  const hp: [number, number] = aIsSide0 ? r.outcome.hpPct : [r.outcome.hpPct[1], r.outcome.hpPct[0]]
  return { winner, how: r.outcome.how, hpPct: hp, ticks: r.outcome.ticks }
}

/** Records a result; KO'd fighters withdraw, elimination losers are out; the next round is built when a round completes. */
export function recordMatch(input: TournamentState, index: number, result: MatchResult, playerTechUses: Record<string, number> = {}): TournamentState {
  const t = structuredClone(input)
  const match = t.matches[index]
  if (!match || match.result) return input
  match.result = result
  if (result.how === 'ko' && result.winner !== null) {
    const loser = result.winner === 0 ? match.b : match.a
    if (!t.koOut.includes(loser)) t.koOut.push(loser)
  }
  if (match.a === 0 || match.b === 0) {
    t.playerTechUses = mergeUses(t.playerTechUses ?? {}, playerTechUses)
  }
  if (isElimination(t)) {
    if (result.winner !== null) {
      const loser = result.winner === 0 ? match.b : match.a
      if (!t.eliminated.includes(loser)) t.eliminated.push(loser)
    } else {
      // A drawn elimination match: the higher HP % advances; equal → the lower index.
      const loser = result.hpPct[0] >= result.hpPct[1] ? match.b : match.a
      if (!t.eliminated.includes(loser)) t.eliminated.push(loser)
    }
    const round = match.round
    const inRound = t.matches.filter((m) => m.round === round)
    if (inRound.every((m) => m.result !== null)) {
      const winners = inRound.map((m) => (t.eliminated.includes(m.a) ? m.b : m.a))
      if (winners.length >= 2) {
        for (let i = 0; i + 1 < winners.length; i += 2) t.matches.push({ round: round + 1, a: winners[i]!, b: winners[i + 1]!, result: null })
      }
    }
  } else {
    // Round robin: a KO'd fighter forfeits the rest of their matches.
    for (const m of t.matches) {
      if (m.result) continue
      const aOut = t.koOut.includes(m.a)
      const bOut = t.koOut.includes(m.b)
      if (aOut && bOut) m.result = { winner: null, how: 'walkover', hpPct: [0, 0] }
      else if (aOut) m.result = { winner: 1, how: 'walkover', hpPct: [0, 1000] }
      else if (bOut) m.result = { winner: 0, how: 'walkover', hpPct: [1000, 0] }
    }
  }
  return t
}

function mergeUses(a: Record<string, number>, b: Record<string, number>): Record<string, number> {
  const out = { ...a }
  for (const [k, n] of Object.entries(b)) out[k] = (out[k] ?? 0) + n
  return out
}

/** Fights one unplayed match with both sides on the CPU. */
function simulateMatch(t: TournamentState, index: number): TournamentState {
  const s = matchSetup(t, index)
  const r = runBattle(s.a, s.b, s.options)
  const match = t.matches[index]!
  const uses = match.a === 0 ? r.fighters[0].techUses : match.b === 0 ? r.fighters[1].techUses : {}
  return recordMatch(t, index, matchResultFrom(r, true), uses)
}

/** Fights the unplayed matches of one round that don't involve the player (never another round's). */
export function simulateRound(input: TournamentState, round: number): TournamentState {
  let t = input
  for (let guard = 0; guard < 64; guard++) {
    const index = t.matches.findIndex((m) => m.round === round && m.result === null && m.a !== 0 && m.b !== 0)
    if (index < 0) break
    t = simulateMatch(t, index)
  }
  return t
}

/**
 * Plays the cup forward round by round: each round's other matches, stopping at the player's next match (unless
 * `includePlayer`, which fights it on the CPU too). Never simulates a match in a round after the player's next one.
 */
export function simulatePending(input: TournamentState, includePlayer = false): TournamentState {
  let t = input
  for (let guard = 0; guard < 64; guard++) {
    const round = currentRound(t)
    if (round === null) break
    t = simulateRound(t, round)
    const mine = t.matches.findIndex((m) => m.round === round && m.result === null && (m.a === 0 || m.b === 0))
    if (mine >= 0) {
      if (!includePlayer) break
      t = simulateMatch(t, mine)
    }
  }
  return t
}

export function isComplete(t: TournamentState): boolean {
  if (t.matches.some((m) => m.result === null)) return false
  if (isElimination(t)) {
    const n = t.participants.length
    return t.eliminated.length >= n - 1
  }
  return true
}

/* ---------- standings ---------- */

export interface Standing {
  index: number
  points: number
  wins: number
  /** Losses include walkovers (a KO'd fighter's remaining matches). */
  losses: number
  draws: number
  /** KO wins. */
  kos: number
  /** Total HP % (tenths) remaining over the matches. */
  hp: number
  place: number
}

/** An elimination match's loser (a draw: the lower HP % goes out; equal → side `b`, as `recordMatch` decides). */
function loserOf(m: MatchRecord): number {
  const r = m.result!
  if (r.winner !== null) return r.winner === 0 ? m.b : m.a
  return r.hpPct[0] >= r.hpPct[1] ? m.b : m.a
}

function pointsFor(m: MatchRecord, who: number): number {
  const r = m.result
  if (!r) return 0
  const side = m.a === who ? 0 : 1
  if (r.winner === null) return r.how === 'walkover' ? 0 : TOURNAMENT.points.draw
  if (r.winner === side) return r.how === 'ko' ? TOURNAMENT.points.koWin : TOURNAMENT.points.win
  return TOURNAMENT.points.loss
}

/**
 * Round robin: points, then head-to-head, KO count, HP % (§13). Elimination: by the round reached.
 * With `upToRound`, only matches in rounds up to it count (the table "after round r").
 */
export function standings(t: TournamentState, upToRound?: number): Standing[] {
  const n = t.participants.length
  const counted = t.matches.filter((m) => m.result !== null && (upToRound === undefined || m.round <= upToRound))
  const rows: Standing[] = Array.from({ length: n }, (_, i) => ({ index: i, points: 0, wins: 0, losses: 0, draws: 0, kos: 0, hp: 0, place: 0 }))
  for (const m of counted) {
    for (const who of [m.a, m.b]) {
      const row = rows[who]!
      const side = m.a === who ? 0 : 1
      row.points += pointsFor(m, who)
      if (m.result!.winner === side) {
        row.wins += 1
        if (m.result!.how === 'ko') row.kos += 1
      } else if (m.result!.winner === null && m.result!.how !== 'walkover') row.draws += 1
      else row.losses += 1
      row.hp += m.result!.hpPct[side]
    }
  }
  if (isElimination(t)) {
    const roundOut = (i: number) => {
      const lost = counted.find((m) => (m.a === i || m.b === i) && loserOf(m) === i)
      return lost ? lost.round : Number.MAX_SAFE_INTEGER
    }
    const sorted = [...rows].sort((x, y) => roundOut(y.index) - roundOut(x.index) || y.hp - x.hp)
    sorted.forEach((row, i) => {
      // Losers of the same round share a placing: 1, 2, 3, 3, 5, 5, 5, 5.
      row.place = i === 0 ? 1 : roundOut(row.index) === roundOut(sorted[i - 1]!.index) ? sorted[i - 1]!.place : i + 1
    })
    return sorted
  }
  const headToHead = (x: Standing, y: Standing) => {
    const m = counted.find((mm) => (mm.a === x.index && mm.b === y.index) || (mm.a === y.index && mm.b === x.index))
    if (!m || !m.result || m.result.winner === null) return 0
    const xWon = (m.a === x.index && m.result.winner === 0) || (m.b === x.index && m.result.winner === 1)
    return xWon ? -1 : 1
  }
  const sorted = [...rows].sort((x, y) => y.points - x.points || headToHead(x, y) || y.kos - x.kos || y.hp - x.hp)
  sorted.forEach((row, i) => {
    row.place = i + 1
  })
  return sorted
}

export function playerPlacing(t: TournamentState): number {
  return standings(t).find((s) => s.index === 0)!.place
}

/** Places gained since the previous round (positive = moved up), by participant; empty for round 1. */
export function placeChanges(t: TournamentState, round: number): Map<number, number> {
  const out = new Map<number, number>()
  if (round <= 1) return out
  const before = new Map(standings(t, round - 1).map((s) => [s.index, s.place]))
  for (const s of standings(t, round)) out.set(s.index, (before.get(s.index) ?? s.place) - s.place)
  return out
}

/* ---------- the elimination bracket ---------- */

export type SlotSide = { kind: 'p'; index: number } | { kind: 'winnerOf'; round: number; slot: number }

export interface BracketSlot {
  round: number
  slot: number
  /** The match's index once it exists. */
  match: number | null
  a: SlotSide
  b: SlotSide
}

function slotWinner(t: TournamentState, s: BracketSlot): number | null {
  if (s.match === null) return null
  const m = t.matches[s.match]!
  if (!m.result) return null
  return loserOf(m) === m.a ? m.b : m.a
}

/**
 * The whole elimination tree, future rounds included: slot j of round r + 1 takes the winners of slots 2j and
 * 2j + 1 of round r (the order `recordMatch` pairs them in). A side not known yet is "winner of" its feeding slot.
 */
export function bracket(t: TournamentState): BracketSlot[][] {
  const rounds: BracketSlot[][] = []
  const total = roundCount(t)
  for (let r = 1; r <= total; r++) {
    const real = t.matches.map((m, i) => ({ m, i })).filter((x) => x.m.round === r)
    const prev = rounds[r - 2]
    const count = r === 1 ? real.length : Math.ceil(prev!.length / 2)
    const slots: BracketSlot[] = []
    for (let j = 0; j < count; j++) {
      const x = real[j]
      if (x) {
        slots.push({ round: r, slot: j, match: x.i, a: { kind: 'p', index: x.m.a }, b: { kind: 'p', index: x.m.b } })
        continue
      }
      const side = (k: number): SlotSide => {
        const feed = prev?.[k]
        const w = feed ? slotWinner(t, feed) : null
        return w !== null ? { kind: 'p', index: w } : { kind: 'winnerOf', round: r - 1, slot: k }
      }
      slots.push({ round: r, slot: j, match: null, a: side(2 * j), b: side(2 * j + 1) })
    }
    rounds.push(slots)
  }
  return rounds
}

export function playerWins(t: TournamentState): number {
  return standings(t).find((s) => s.index === 0)!.wins
}

