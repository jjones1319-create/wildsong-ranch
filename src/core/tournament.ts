export interface TournamentOutcome {
  eventId: string
  placing: number
  participants: number
  playerWins: number
  playerMatches: number
  purse: number
  perWinGold: number
  items: { id: string; qty: number }[]
  sheets: string[]
  fame: number
  growth: Partial<Stats>
  fatigue: number
  stress: number
  lifespan: number
  koed: boolean
  injuredWeeks: number
  died: boolean
  promoted: TournamentGrade | null
  rankBefore: number
  rankAfter: number
  titles: string[]
  crownInvite: boolean
  legendInvite: boolean
  hallOfFame: boolean
  relayTeamWin: boolean | null
}

export function prizeMultiplier(state: GameState, m: Monster): number {
  let pct = DIFFICULTY[state.difficulty].prizeMulPct
  if (traitOf(m) === 'gilded') pct = divRound(pct * TOURNAMENT.gildedPrizePct, 100)
  pct = divRound(pct * variantPrizePct(m), 100)
  return pct
}

function itemPrizes(state: GameState, event: TournamentEvent, grade: TournamentGrade, rng: Rng): { items: { id: string; qty: number }[]; sheets: string[] } {
  const items: { id: string; qty: number }[] = []
  const sheets: string[] = []
  const regular = ITEMS.filter((i) => i.category === 'sweet' && i.effect.kind === 'sweet' && i.effect.amount === 5 && i.effect.stat !== 'all')
  const grand = ITEMS.filter((i) => i.category === 'sweet' && i.effect.kind === 'sweet' && i.effect.amount === 15)
  const addItem = (id: string, qty = 1) => {
    const found = items.find((x) => x.id === id)
    if (found) found.qty += qty
    else items.push({ id, qty })
  }
  const sheetFrom = (families: readonly string[]) => {
    const pool = UNIVERSAL_TECHNIQUES.filter((t) => families.includes(t.family) && !state.songbook.includes(t.id))
    if (pool.length === 0) return false
    sheets.push(rng.pick(pool).id)
    return true
  }
  switch (itemPrizeKind(event, grade)) {
    case 'wondercake':
      addItem('wondercake')
      break
    case 'signature': {
      const sig = signatureOf(state.monster!.mainBreed).id
      if (state.songbook.includes(sig)) addItem('potential-pearl')
      else sheets.push(sig)
      break
    }
    case 'legend':
      addItem('tempo-bell')
      addItem('wondercake', 3)
      break
    case 'shardMask':
      addItem('shard-mask')
      break
    case 'sweets':
      for (let i = 0; i < TOURNAMENT.itemPrizes.lowSweets; i++) addItem(rng.pick(regular).id)
      break
    case 'sheetOrGrand':
      if (rng.chance(50) && sheetFrom(['Basic', 'Hit', 'Wither', 'Sharp'])) break
      addItem(rng.pick(grand).id)
      break
    case 'grandSweets':
      for (let i = 0; i < TOURNAMENT.itemPrizes.highGrandSweets; i++) addItem(rng.pick(grand).id)
      if (rng.chance(TOURNAMENT.itemPrizes.highSheetPct)) sheetFrom(['Heavy', 'Special'])
      break
    case 'none':
      break
  }
  return { items, sheets }
}

function computeRank(guild: GameState['guild']): number {
  const officials = TOURNAMENT.rank.officialGrades.filter((g) => guild.officialsWon.includes(g as TournamentGrade)).length
  const byOfficials = 1 + officials
  const byCrowns = guild.crownsWon.length > 0 ? TOURNAMENT.rank.crownBase + guild.crownsWon.length : 0
  return clamp(Math.max(byOfficials, byCrowns), 1, TOURNAMENT.rank.max)
}

/** Applies the whole cup's consequences (§13, §7) and clears it from the state. Pure. */
export function finishTournament(input: GameState, rng: Rng): { state: GameState; outcome: TournamentOutcome } {
  const state = structuredClone(input)
  const t = state.tournament!
  const event = EVENT_BY_ID[t.eventId]!
  const m = state.monster!
  const grade = m.grade
  const koed = t.koOut.includes(0)
  const placing = playerPlacing(t)
  const wins = playerWins(t)
  const playerMatches = t.matches.filter((x) => x.a === 0 || x.b === 0).length
  const mult = prizeMultiplier(state, m)
  const outcome: TournamentOutcome = {
    eventId: t.eventId,
    placing,
    participants: t.participants.length,
    playerWins: wins,
    playerMatches,
    purse: 0,
    perWinGold: 0,
    items: [],
    sheets: [],
    fame: 0,
    growth: {},
    fatigue: 0,
    stress: 0,
    lifespan: 0,
    koed,
    injuredWeeks: 0,
    died: false,
    promoted: null,
    rankBefore: state.breeder.rank,
    rankAfter: state.breeder.rank,
    titles: [],
    crownInvite: false,
    legendInvite: false,
    hallOfFame: false,
    relayTeamWin: null,
  }

  // Money.
  const base = purseOf(event, grade)
  if (event.kind === 'summit') {
    const teamWins = t.relayWins + wins
    outcome.relayTeamWin = teamWins >= 3
    outcome.purse = divRound(((outcome.relayTeamWin ? TOURNAMENT.summit.teamWin : 0) + TOURNAMENT.summit.perOwnWin * wins) * mult, 100)
  } else {
    const share = TOURNAMENT.purseSplitPct[placing - 1] ?? 0
    outcome.purse = divRound(divRound(base * share, 100) * mult, 100)
    outcome.perWinGold = divRound(TOURNAMENT.perWinGoldPerGrade * gradeIndex(grade) * wins * mult, 100)
  }
  state.money += outcome.purse + outcome.perWinGold
  m.records.earnings += outcome.purse + outcome.perWinGold

  const won = placing === 1 && event.kind !== 'summit'
  // Item prizes for 1st place.
  if (won) {
    const prizes = itemPrizes(state, event, grade, rng)
    outcome.items = prizes.items
    outcome.sheets = prizes.sheets
    for (const p of prizes.items) state.inventory = addItems(state.inventory, p.id, p.qty)
    for (const id of prizes.sheets) state.songbook = addSheet(state.songbook, id)
  }

  // Fame.
  let fame = 0
  if (won) {
    if (event.kind === 'official') fame += TOURNAMENT.fame.officialWin[grade]!
    else if (event.kind === 'crown') fame += TOURNAMENT.fame.crownWin
    else if (event.kind === 'legend') fame += TOURNAMENT.fame.legendWin
    else fame += TOURNAMENT.fame.cupWin[grade]!
    if (traitOf(m) === 'regal') fame += TOURNAMENT.fame.regalBonus
  } else if (placing > 3) fame += TOURNAMENT.fame.noPodium
  const fameBefore = m.fame
  m.fame = clamp(m.fame + fame, RANGES.fame.min, RANGES.fame.max)
  outcome.fame = m.fame - fameBefore

  // Stat growth for the top three.
  if (placing <= 3) {
    const range = TOURNAMENT.growth.range[grade]!
    const picks = rng.shuffle([...STAT_KEYS]).slice(0, TOURNAMENT.growth.stats)
    for (const k of picks) {
      const amount = Math.max(1, rng.nextInt(range[0], range[1]) + m.likes.battle * TOURNAMENT.growth.battleLike)
      const before = m.stats[k]
      m.stats[k] = addStat(before, amount)
      outcome.growth[k] = m.stats[k] - before
    }
  }

  // After-effects (§13 table, §7 lifespan).
  const after = placing === 1 ? TOURNAMENT.after.first : placing <= 3 ? TOURNAMENT.after.podium : TOURNAMENT.after.rest
  outcome.fatigue = after.fatigue + (koed ? TOURNAMENT.after.koFatigue : 0)
  outcome.stress = after.stress
  outcome.lifespan = -(TOURNAMENT.after.lifespan + (koed ? TOURNAMENT.after.koLifespan : 0))
  m.fatigue = addCondition(m.fatigue, outcome.fatigue)
  m.stress = addCondition(m.stress, outcome.stress)
  if (koed) {
    const d = DIFFICULTY[state.difficulty]
    if (d.koInjury && rng.chance(TOURNAMENT.injury.basePct + Math.floor(m.fatigue / TOURNAMENT.injury.fatigueDiv))) {
      outcome.injuredWeeks = rng.nextInt(TOURNAMENT.injury.weeks.min, TOURNAMENT.injury.weeks.max)
      m.status.injuredWeeks = Math.max(m.status.injuredWeeks, outcome.injuredWeeks)
      outcome.lifespan -= TOURNAMENT.injury.lifespan
    }
    if (d.koDeathPct > 0 && m.fatigue >= TOURNAMENT.koDeathFatigueMin && rng.chance(d.koDeathPct)) {
      outcome.died = true
      state.ended = 'passed'
    }
  }
  m.lifespanTotal = clamp(m.lifespanTotal + outcome.lifespan, RANGES.lifespan.min, RANGES.lifespan.max)

  // Records.
  for (const match of t.matches) {
    if (match.a !== 0 && match.b !== 0) continue
    const r = match.result
    if (!r) continue
    const side = match.a === 0 ? 0 : 1
    if (r.winner === null) {
      if (r.how !== 'walkover') m.records.draws += 1
    } else if (r.winner === side) {
      m.records.wins += 1
      if (r.how === 'ko') m.records.kos += 1
    } else m.records.losses += 1
  }
  if (won) m.records.cupsWon += 1
  for (const [id, n] of Object.entries(t.playerTechUses ?? {})) for (let i = 0; i < n; i++) state.monster = recordUse(state.monster!, id)
  const mm = state.monster!

  // Promotion, rank, invitations, Hall of Fame, titles.
  const addTitle = (title: string) => {
    if (state.titles.includes(title)) return
    state.titles.push(title)
    if (!mm.records.titles.includes(title)) mm.records.titles.push(title)
    outcome.titles.push(title)
  }
  const newMail = (kind: GameState['mail'][number]['kind'], ref: string) => state.mail.unshift({ id: `${state.week}-${kind}-${ref}`, week: state.week, kind, ref, read: false })
  if (won) {
    if (event.kind !== 'official' && event.kind !== 'crown' && event.kind !== 'legend') addTitle('First Ribbon')
    if (event.kind === 'official') {
      addTitle('Ascended')
      if (grade === 'S') addTitle('S-Class Breeder')
      if (!state.guild.officialsWon.includes(grade)) state.guild.officialsWon.push(grade)
      const gi = TOURNAMENT_GRADES.indexOf(grade)
      if (gi < TOURNAMENT_GRADES.length - 1) {
        mm.grade = TOURNAMENT_GRADES[gi + 1]!
        outcome.promoted = mm.grade
        newMail('promotion', mm.grade)
      }
      if (grade === 'S' && !state.guild.crownInvite) {
        state.guild.crownInvite = true
        outcome.crownInvite = true
        newMail('crown', 'invite')
      }
    }
    if (event.kind === 'crown' && event.crownId) {
      addTitle('Crowned')
      if (loyaltyOf(mm) >= 100) addTitle('Iron Bond')
      mm.records.crownsWon += 1
      if (!state.guild.crownsWon.includes(event.crownId)) state.guild.crownsWon.push(event.crownId)
      state.guild.crownInvite = true
      if (state.guild.crownsWon.length >= 4) {
        addTitle('Four Crowns')
        if (!state.guild.legendInvite && !state.guild.legendWon) {
          state.guild.legendInvite = true
          outcome.legendInvite = true
          newMail('legend', 'invite')
        }
        // CONTENT §11: the Guild presents the Wyrm Scale once; offered at the Shrine it wakes Aurelwyrm.
        if (!state.unlocks.wyrmScaleGiven) {
          state.unlocks.wyrmScaleGiven = true
          state.inventory = addItems(state.inventory, 'wyrm-scale', 1)
          outcome.items.push({ id: 'wyrm-scale', qty: 1 })
          newMail('wyrm', 'scale')
        }
      }
    }
    state.records.cupsWon += 1
    if (event.kind === 'legend') {
      addTitle('Legend of the Vale')
      state.guild.legendWon = true
      state.guild.legendInvite = false
      state.hallOfFame.push({ monster: structuredClone(mm), week: state.week })
      outcome.hallOfFame = true
    }
  }
  if (gradeIndex(mm.grade) > gradeIndex(mm.records.highestGrade)) mm.records.highestGrade = mm.grade
  const rank = computeRank(state.guild)
  if (rank > state.breeder.rank) {
    state.breeder.rank = rank
    newMail('rank', String(rank))
    if (rank >= TOURNAMENT.rank.max) addTitle('Grand Breeder')
  }
  outcome.rankAfter = state.breeder.rank

  state.tournament = null
  return { state, outcome }
}

/** The "too easy" cost of entering below your grade, paid at entry (§13). */
export function applyTooEasy(input: GameState): GameState {
  const state = structuredClone(input)
  const m = state.monster!
  m.fame = clamp(m.fame + TOURNAMENT.tooEasy.fame, RANGES.fame.min, RANGES.fame.max)
  m.spoil = addCondition(m.spoil, TOURNAMENT.tooEasy.spoil)
  m.fear = addCondition(m.fear, TOURNAMENT.tooEasy.fear)
  return state
}

export interface RelayLeg {
  grade: TournamentGrade
  /** True for the player's own leg (the cup's real match). */
  player: boolean
  vale: Participant | null
  coast: Participant | null
  /** From the Vale's side (`a`). */
  result: MatchResult | null
}

/**
 * The Summit relay's five legs (§13): the player's grade is the player's own, fightable leg; the four NPC legs are
 * fought here between generated Vale and Coast teammates. Deterministic from the cup's seed, so the legs can be
 * shown again at any time and always match the win count stored at entry.
 */
export function relayLegs(t: TournamentState, playerGrade: TournamentGrade): RelayLeg[] {
  const rng = createRng(t.seed ^ 0x5a17)
  const legs: RelayLeg[] = []
  for (const slot of TOURNAMENT.summit.slots) {
    const grade = slot as TournamentGrade
    if (slot === playerGrade) {
      legs.push({ grade, player: true, vale: null, coast: null, result: null })
      continue
    }
    const g = slot as NpcGrade
    const vale = wildParticipant(g, rng)
    const coast = wildParticipant(g, rng)
    const r = runBattle(
      { monster: vale.monster, control: 'ai', personality: vale.personality, tier: tierOfGrade(vale.monster.grade) },
      { monster: coast.monster, control: 'ai', personality: coast.personality, tier: tierOfGrade(coast.monster.grade) },
      matchOptions(rng.nextU32()),
    )
    legs.push({ grade, player: false, vale, coast, result: matchResultFrom(r, true) })
  }
  return legs
}

/** The Summit relay: four NPC teammates fight their grade's slot; the Vale's wins are counted. */
export function simulateRelay(t: TournamentState, playerGrade: TournamentGrade): number {
  return relayLegs(t, playerGrade).filter((l) => !l.player && l.result?.winner === 0).length
}

export function eventName(id: string): string {
  return EVENT_BY_ID[id]?.name ?? id
}
