import { mkdirSync, writeFileSync } from 'node:fs'
import { expect, test, type Page } from '@playwright/test'

/**
 * VISUAL_V1_EFFECTS §8, the mandatory review step: drive the Effects Lab with a manual fx clock, capture every
 * primitive at every element at two moments, and compose one contact sheet per element in docs/fx-review/.
 * Run on the Pixel 7 profile only:  npx playwright test --project pixel-7 e2e/fx-review.spec.ts
 */
const BASE = '/wildsong-ranch/'
const ELEMENTS = ['Fire', 'Water', 'Ice', 'Lightning', 'Wind', 'Earth', 'Nature', 'Light', 'Dark', 'Sound', 'Physical'] as const
/** Primitive → the two fx-clock moments (ms) that show it best. */
const MOMENTS: Record<string, [number, number]> = {
  burst: [110, 330],
  cone: [260, 560],
  trail: [160, 380],
  projectile: [150, 330],
  beam: [60, 170],
  ring: [110, 300],
  impact: [60, 200],
  splash: [120, 380],
  sheet: [300, 650],
  lightning: [40, 150],
  haze: [300, 800],
  glow: [250, 600],
  debris: [150, 450],
  mist: [300, 900],
  flash: [20, 70],
  shake: [40, 120],
  hitstop: [30, 90],
  impactFrame: [10, 25],
}
const OUT = 'docs/fx-review'

declare global {
  interface Window {
    __fx?: { fire: (name: string, element: string, strength?: number) => void; clear: () => void; step: (ms: number) => void; stats: () => unknown; ready: boolean }
  }
}

async function openLab(page: Page): Promise<void> {
  await page.goto(`${BASE}?fxmanual=1#lab/effects`)
  await page.waitForFunction(() => window.__fx?.ready === true, undefined, { timeout: 30_000 })
  // Let the camera settle and the first render land.
  await page.waitForTimeout(400)
}

test.describe.configure({ mode: 'serial' })

test('contact sheets of every primitive at every element', async ({ page, browser }, testInfo) => {
  test.skip(testInfo.project.name !== 'pixel-7', 'one profile is enough for the review')
  test.setTimeout(1_200_000)
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  page.on('console', (m) => {
    if (m.type() === 'error') errors.push(m.text())
  })
  await openLab(page)
  mkdirSync(OUT, { recursive: true })
  const arena = page.locator('.arena')
  const composer = await browser.newPage({ viewport: { width: 1860, height: 1200 }, deviceScaleFactor: 1 })
  for (const element of ELEMENTS) {
    const tiles: { name: string; ms: number; png: Buffer }[] = []
    for (const [name, moments] of Object.entries(MOMENTS)) {
      for (const ms of moments) {
        await page.evaluate(
          ([n, el, t]) => {
            const fx = window.__fx!
            fx.clear()
            fx.step(1)
            fx.fire(n as string, el as string, 0.9)
            fx.step(t as number)
          },
          [name, element, ms],
        )
        // Hit-stop / impact-frame flags go through Preact state: give the DOM a frame.
        await page.waitForTimeout(40)
        tiles.push({ name, ms, png: await arena.screenshot({ animations: 'disabled', caret: 'hide', timeout: 60_000 }) })
      }
    }
    await page.evaluate(() => window.__fx!.clear())
    // Compose this element's sheet right away: 6 tiles across (3 primitives × 2 moments per row).
    const sheet = { element, tiles }
    const cells = sheet.tiles
      .map((t) => `<figure><img src="data:image/png;base64,${t.png.toString('base64')}"><figcaption>${t.name} · ${t.ms} ms</figcaption></figure>`)
      .join('')
    await composer.setContent(
      `<!doctype html><html><head><meta charset="utf-8"><style>
        body{margin:0;background:#1b1f24;color:#e8e2d6;font:13px system-ui;padding:12px}
        h1{font-size:18px;margin:0 0 10px}
        .grid{display:grid;grid-template-columns:repeat(6,1fr);gap:8px}
        figure{margin:0;background:#0e1114;border-radius:6px;overflow:hidden}
        img{display:block;width:100%;height:auto}
        figcaption{padding:3px 6px;font-size:12px;color:#b8b2a8}
      </style></head><body><h1>Wildsong Ranch · V1 effects review · ${sheet.element} (Pixel 7 profile, manual clock)</h1><div class="grid">${cells}</div></body></html>`,
    )
    const png = await composer.screenshot({ fullPage: true, timeout: 120_000 })
    writeFileSync(`${OUT}/${sheet.element.toLowerCase()}.png`, png)
  }
  await composer.close()
  writeFileSync(`${OUT}/README.md`, readme())
  expect(errors, errors.join('\n')).toEqual([])
})

function readme(): string {
  return `# V1 effects review (contact sheets)

Generated by \`npx playwright test --project pixel-7 e2e/fx-review.spec.ts\` from the Effects Lab with a manual fx clock
(\`?fxmanual=1#lab/effects\`): every primitive at every element, two moments each, on the Pixel 7 profile at Standard
intensity and Ultra quality. One PNG per element. Look at them after any change to \`src/fx/elements.ts\` or a primitive.
`
}
